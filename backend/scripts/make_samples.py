"""Generate the bundled SYNTHETIC sample pairs (data/samples) and copy them to the frontend.

    python scripts/make_samples.py

The samples are procedurally generated test scenes, NOT real satellite imagery.
They are labelled as synthetic everywhere they are shown.
"""
from __future__ import annotations

import json
import shutil
import sys
from pathlib import Path

from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from app.core.config import REPO_ROOT  # noqa: E402
from app.utils.synthetic import generate_pair  # noqa: E402

SAMPLES = [
    ("urban_expansion", 11, "Synthetic urban expansion",
     "New buildings and a road segment appear east of a small town."),
    ("flood_extent", 23, "Synthetic river flood extent",
     "A river widens over adjacent fields - illustrates potential flood-related surface change."),
    ("vegetation_clearing", 37, "Synthetic vegetation clearing",
     "Two forest patches are cleared to bare soil."),
]
NOTE = ("SYNTHETIC: procedurally generated by PROJECT ORBIT (app/utils/synthetic.py). Not real satellite "
        "imagery. The AFTER image includes a deliberate ~1.2 deg rotation, a (5,-3) px shift, an illumination "
        "change and sensor noise so that alignment and robustness can be demonstrated. Ground truth is exact.")


def main() -> None:
    out = REPO_ROOT / "data" / "samples"
    out.mkdir(parents=True, exist_ok=True)
    manifest = {"note": NOTE, "license": "MIT (generated content, same license as this repository)", "samples": []}
    for scenario, seed, title, desc in SAMPLES:
        before, after, gt = generate_pair(scenario, seed=seed)
        files = {"before": f"{scenario}_before.png", "after": f"{scenario}_after.png",
                 "ground_truth": f"{scenario}_gt.png"}
        Image.fromarray(before).save(out / files["before"])
        Image.fromarray(after).save(out / files["after"])
        Image.fromarray(gt).save(out / files["ground_truth"])
        manifest["samples"].append({
            "id": scenario, "title": title, "description": desc, "synthetic": True,
            "source": "PROJECT ORBIT procedural generator", "width": before.shape[1], "height": before.shape[0],
            "files": files,
        })
        print(f"wrote {scenario} ({gt.astype(bool).mean() * 100:.2f}% changed pixels in ground truth)")
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")

    public = REPO_ROOT / "frontend" / "public" / "samples"
    public.mkdir(parents=True, exist_ok=True)
    for s in manifest["samples"]:
        for f in s["files"].values():
            shutil.copy2(out / f, public / f)
    print(f"manifest + {len(manifest['samples'])} samples written to {out} and copied to {public}")


if __name__ == "__main__":
    main()
