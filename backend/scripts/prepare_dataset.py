"""Dataset preparation utilities.

Commands
--------
verify     Check a LEVIR-CD-style dataset (structure, pairing, sizes, label values).
           python scripts/prepare_dataset.py verify --root D:/datasets/LEVIR-CD

tile       Pre-crop 1024x1024 LEVIR-CD images into 256x256 tiles (faster training on CPU).
           python scripts/prepare_dataset.py tile --root D:/datasets/LEVIR-CD --out D:/datasets/LEVIR-CD-256

synthetic  Write a SMALL synthetic dataset in the same layout, for smoke-testing the
           training/evaluation code offline. Not suitable for training a real model.
           python scripts/prepare_dataset.py synthetic --out ../data/synthetic_cd
"""
from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from pathlib import Path

import numpy as np
from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from app.models.dataset import list_pairs  # noqa: E402
from app.utils.synthetic import SCENARIOS, generate_pair  # noqa: E402

SPLITS = ("train", "val", "test")


def verify(root: Path) -> dict:
    report = {"root": root.name, "splits": {}, "ok": True}
    for split in SPLITS:
        try:
            pairs = list_pairs(root, split)
        except FileNotFoundError as exc:
            report["splits"][split] = {"error": str(exc)}
            report["ok"] = False
            continue
        sizes, label_values, change_ratio = Counter(), set(), []
        for a, b, lab in pairs:
            with Image.open(a) as ia, Image.open(b) as ib, Image.open(lab) as il:
                if ia.size != ib.size or ia.size != il.size:
                    report["ok"] = False
                    report.setdefault("mismatched", []).append(a.name)
                sizes[f"{ia.size[0]}x{ia.size[1]}"] += 1
                m = np.array(il.convert("L"))
                label_values.update(np.unique(m).tolist())
                change_ratio.append(float((m > 127).mean()))
        n_a = len(list((root / split / "A").iterdir()))
        report["splits"][split] = {
            "pairs": len(pairs), "unpaired_files_in_A": n_a - len(pairs), "sizes": dict(sizes),
            "label_values": sorted(label_values)[:10],
            "mean_change_ratio": round(float(np.mean(change_ratio)), 5) if change_ratio else None,
        }
        if not pairs:
            report["ok"] = False
    return report


def tile(root: Path, out: Path, size: int) -> None:
    for split in SPLITS:
        pairs = list_pairs(root, split)
        for sub in ("A", "B", "label"):
            (out / split / sub).mkdir(parents=True, exist_ok=True)
        n = 0
        for a, b, lab in pairs:
            ims = [Image.open(p) for p in (a, b, lab)]
            w, h = ims[0].size
            for y in range(0, h - size + 1, size):
                for x in range(0, w - size + 1, size):
                    name = f"{a.stem}_{y}_{x}.png"
                    for im, sub in zip(ims, ("A", "B", "label")):
                        im.crop((x, y, x + size, y + size)).save(out / split / sub / name)
                    n += 1
            for im in ims:
                im.close()
        print(f"{split}: {len(pairs)} images -> {n} tiles")


def synthetic(out: Path, counts: dict[str, int], size: int) -> None:
    seed = 1000
    for split, n in counts.items():
        for sub in ("A", "B", "label"):
            (out / split / sub).mkdir(parents=True, exist_ok=True)
        for i in range(n):
            scenario = SCENARIOS[i % len(SCENARIOS)]
            # misalign=False: real CD datasets are distributed co-registered
            before, after, gt = generate_pair(scenario, seed=seed, size=size, misalign=False)
            seed += 1
            name = f"{split}_{i:04d}.png"
            Image.fromarray(before).save(out / split / "A" / name)
            Image.fromarray(after).save(out / split / "B" / name)
            Image.fromarray(gt).save(out / split / "label" / name)
        print(f"{split}: wrote {n} synthetic pairs")
    (out / "README.txt").write_text(
        "SYNTHETIC smoke-test dataset generated by PROJECT ORBIT (scripts/prepare_dataset.py synthetic).\n"
        "Not real satellite imagery. Use only to verify that training/evaluation code runs.\n", encoding="utf-8")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    v = sub.add_parser("verify")
    v.add_argument("--root", type=Path, required=True)
    t = sub.add_parser("tile")
    t.add_argument("--root", type=Path, required=True)
    t.add_argument("--out", type=Path, required=True)
    t.add_argument("--size", type=int, default=256)
    s = sub.add_parser("synthetic")
    s.add_argument("--out", type=Path, required=True)
    s.add_argument("--train", type=int, default=24)
    s.add_argument("--val", type=int, default=6)
    s.add_argument("--test", type=int, default=6)
    s.add_argument("--size", type=int, default=256)
    args = ap.parse_args()

    if args.cmd == "verify":
        rep = verify(args.root)
        print(json.dumps(rep, indent=2))
        sys.exit(0 if rep["ok"] else 1)
    elif args.cmd == "tile":
        tile(args.root, args.out, args.size)
    else:
        synthetic(args.out, {"train": args.train, "val": args.val, "test": args.test}, args.size)


if __name__ == "__main__":
    main()
